#!/usr/bin/env node
/**
 * Seeds the admin-editable tables from the code defaults (src/shared/data/defaults.ts and
 * settingsSchema.ts): site_settings, team_members, series_chapters, series_characters.
 * site_content is NOT seeded (empty = defaults from messages/*.json).
 *
 * Idempotent and non-destructive: rows that already exist are left alone, so re-running never
 * overwrites admin edits. team_members is seeded only while the table is empty.
 *   --force   overwrite existing settings / series rows with the code defaults (team untouched)
 *
 * Usage: node --env-file=.env.local scripts/seed-content.mjs [--force]
 *
 * The defaults live in TypeScript; they are transpiled on the fly with the repo's `typescript`.
 */

import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { createClient } from "@supabase/supabase-js";
import ts from "typescript";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "src");
const nodeRequire = createRequire(import.meta.url);
const force = process.argv.includes("--force");

const cache = new Map();
function load(file) {
  if (cache.has(file)) return cache.get(file).exports;
  const mod = { exports: {} };
  cache.set(file, mod);
  if (file.endsWith(".json")) {
    mod.exports = JSON.parse(readFileSync(file, "utf8"));
    return mod.exports;
  }
  const { outputText } = ts.transpileModule(readFileSync(file, "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true, resolveJsonModule: true },
    fileName: file,
  });
  const req = (spec) => {
    let target = null;
    if (spec.startsWith("@/")) target = path.join(SRC, spec.slice(2));
    else if (spec.startsWith(".")) target = path.resolve(path.dirname(file), spec);
    if (!target) return nodeRequire(spec);
    for (const candidate of [target, `${target}.ts`, `${target}.tsx`, `${target}.js`, `${target}.json`, path.join(target, "index.ts")]) {
      try {
        readFileSync(candidate);
        return load(candidate);
      } catch (e) {
        if (e.code !== "ENOENT" && e.code !== "EISDIR") throw e;
      }
    }
    throw new Error(`Cannot resolve ${spec} from ${file}`);
  };
  new Function("require", "exports", "module", outputText)(req, mod.exports, mod);
  return mod.exports;
}

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error("Missing NEXT_PUBLIC_SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY (use --env-file=.env.local).");
  process.exit(1);
}
const supabase = createClient(url, key, { auth: { persistSession: false } });

const { TEAM_DEFAULTS, CHAPTER_DEFAULTS, CHARACTER_DEFAULTS } = load(path.join(SRC, "shared/data/defaults.ts"));
const { SETTING_DEFAULTS, validateSetting } = load(path.join(SRC, "shared/data/settingsSchema.ts"));

const omit = (row, keys) => Object.fromEntries(Object.entries(row).filter(([k]) => !keys.includes(k)));
const stripTimes = (row) => omit(row, ["created_at", "updated_at"]);
const check = (label, { error }) => {
  if (error) {
    console.error(`${label}: ${error.message}`);
    process.exit(1);
  }
};
const upsert = (table, rows, onConflict) =>
  supabase.from(table).upsert(rows, { onConflict, ignoreDuplicates: !force });

// settings
const settings = Object.entries(SETTING_DEFAULTS).map(([k, v]) => {
  const r = validateSetting(k, v);
  if (!r.ok) throw new Error(`Default for setting "${k}" is invalid: ${r.error}`);
  return { key: k, value: r.value };
});
check("site_settings", await upsert("site_settings", settings, "key"));
console.log(`site_settings: ${settings.length} keys (${force ? "overwritten" : "missing ones inserted"})`);

// series
check("series_chapters", await upsert("series_chapters", CHAPTER_DEFAULTS.map(stripTimes), "slug"));
console.log(`series_chapters: ${CHAPTER_DEFAULTS.length} rows`);
check("series_characters", await upsert("series_characters", CHARACTER_DEFAULTS.map(stripTimes), "slug"));
console.log(`series_characters: ${CHARACTER_DEFAULTS.length} rows`);

// team: only when empty (ids are generated by the database)
const { count, error: countError } = await supabase.from("team_members").select("id", { count: "exact", head: true });
check("team_members count", { error: countError });
if ((count ?? 0) === 0) {
  const rows = TEAM_DEFAULTS.map((row) => omit(row, ["id", "created_at", "updated_at"])); // ids are generated by the database
  check("team_members", await supabase.from("team_members").insert(rows));
  console.log(`team_members: ${rows.length} rows inserted`);
} else {
  console.log(`team_members: ${count} rows already present, left alone`);
}
